#!/usr/bin/env bash
# Writes the git-ignored .r2-secrets.sh at the repo root from 1Password, for scripts/eval-data.mjs.
# It refuses to overwrite an existing file; pass --force after a key rotation.
#
#   bash scripts/r2-secrets-init.sh [--force]
#
# R2_OP_ITEM names the 1Password item (default "op://Private/cc-toolkit R2 Bucket") and OP_ACCOUNT the account
# (default my.1password.com). The values go straight from `op read` into the file and are never printed.
set -euo pipefail

out="$(cd "$(dirname "$0")/.." && pwd)/.r2-secrets.sh"
item="${R2_OP_ITEM:-op://Private/cc-toolkit R2 Bucket}"
account="${OP_ACCOUNT:-my.1password.com}"

if [[ -e "$out" && "${1:-}" != "--force" ]]; then
  echo "$out already exists; pass --force to rewrite it" >&2
  exit 1
fi

quote() { printf "'%s'" "${1//\'/\'\\\'\'}"; }

tmp="$(mktemp "$out.XXXXXX")"
trap 'rm -f "$tmp"' EXIT
chmod 600 "$tmp"
{
  echo "# Generated by scripts/r2-secrets-init.sh. Never commit or print this file."
  for pair in "R2_ACCOUNT_ID=account id" "R2_ACCESS_KEY_ID=Access Key ID" \
    "R2_SECRET_ACCESS_KEY=Secret Access Key" "R2_BUCKET=bucket name"; do
    value="$(op read --account "$account" "$item/${pair#*=}")"
    echo "export ${pair%%=*}=$(quote "$value")"
  done
} >"$tmp"
mv "$tmp" "$out"
trap - EXIT
echo "wrote $out"
